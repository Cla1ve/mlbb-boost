function renderMainSitemap(posts, staticPages) {
  const entries = [];
  for (const page of staticPages) {
    entries.push({ loc: absoluteUrl(page.pathname), lastmod: page.lastmod });
  }
  const archiveLastmod = (posts.length
    ? posts.reduce((latest, post) => (
        new Date(post.dateModified) > new Date(latest) ? post.dateModified : latest
      ), posts[0].dateModified)
    : NEWS_LAUNCH_ISO).slice(0, 10);
  for (const locale of LOCALE_KEYS) {
    entries.push({
      loc: localeRootUrl(locale),
      lastmod: archiveLastmod,
      alternates: {
        ru: localeRootUrl('ru'),
        en: localeRootUrl('en'),
        'x-default': localeRootUrl('ru')
      }
    });
  }
  for (const post of posts) {
    for (const locale of LOCALE_KEYS) {
      entries.push({
        loc: articleUrl(post, locale),
        lastmod: post.dateModified.slice(0, 10),
        alternates: {
          ru: articleUrl(post, 'ru'),
          en: articleUrl(post, 'en'),
          'x-default': articleUrl(post, 'ru')
        }
      });
    }
  }

  const unique = [...new Map(entries.map((entry) => [entry.loc, entry])).values()];
  return `<?xml version="1.0" encoding="UTF-8"?>
${GENERATED_MARKER}
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${unique.map((entry) => `  <url>
    <loc>${escapeXml(entry.loc)}</loc>
    <lastmod>${escapeXml(entry.lastmod)}</lastmod>${entry.alternates ? `
    ${Object.entries(entry.alternates).map(([language, href]) => `<xhtml:link rel="alternate" hreflang="${language}" href="${escapeXml(href)}"/>`).join('\n    ')}` : ''}
  </url>`).join('\n')}
</urlset>
`;
}

async function preparePublishedPosts(data) {
  if (!data || !Array.isArray(data.posts)) {
    throw new Error('content/news/posts.json должен содержать массив posts.');
  }

  const slugs = new Set();
  const categoryLabels = new Map();
  const allowedStatuses = new Set(['published', 'draft']);
  for (const post of data.posts) {
    if (!allowedStatuses.has(post?.status)) {
      throw new Error(`Неизвестный status у ${post?.slug || 'материала без slug'}: ${post?.status || 'пусто'}.`);
    }
    const errors = validatePost(post, { allowDraft: post.status === 'draft' });
    if (errors.length) {
      throw new Error(`Ошибка в ${post.slug || 'без slug'}:\n- ${errors.join('\n- ')}`);
    }
    if (slugs.has(post.slug)) throw new Error(`Повторяющийся slug: ${post.slug}`);
    slugs.add(post.slug);
    const categoryKey = post.categoryKey;
    const existingCategory = categoryLabels.get(categoryKey);
    if (existingCategory && existingCategory !== post.category) {
      throw new Error(
        `Категории "${existingCategory}" и "${post.category}" отличаются только регистром. ` +
        'Используйте одно написание, чтобы фильтр не дублировался.'
      );
    }
    categoryLabels.set(categoryKey, post.category);
    await Promise.all(LOCALE_KEYS.map((locale) => assertHeroExists(localizePost(post, locale))));
  }

  return [...data.posts]
    .filter((post) => post.status === 'published')
    .sort((a, b) => new Date(b.datePublished) - new Date(a.datePublished));
}

function renderGeneratedFiles(posts, staticPages) {
  const files = new Map([
    [path.join(SITE_ROOT, 'news-sitemap.xml'), renderNewsSitemap(posts)],
    [path.join(SITE_ROOT, 'sitemap.xml'), renderMainSitemap(posts, staticPages)]
  ]);
  for (const locale of LOCALE_KEYS) {
    const localizedPosts = posts.map((post) => localizePost(post, locale));
    const config = localeConfig(locale);
    files.set(path.join(config.rootDir, 'index.html'), renderIndex(localizedPosts, { locale }));
    files.set(path.join(config.rootDir, 'rss.xml'), renderRss(localizedPosts, locale));
    for (const post of localizedPosts) {
      files.set(articlePath(post, locale), renderArticle(post, { locale }));
    }
  }
  for (const [filePath, content] of files) {
    files.set(filePath, content.replace(/[ \t]+$/gm, ''));
  }
  return files;
}

async function writeGeneratedFiles(files) {
  const staged = [];
  const originals = new Map();
  const committed = [];
  try {
    for (const [filePath, content] of files) {
      await mkdir(path.dirname(filePath), { recursive: true });
      try {
        originals.set(filePath, { exists: true, content: await readFile(filePath, 'utf8') });
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
        originals.set(filePath, { exists: false, content: '' });
      }
      const tempPath = `${filePath}.${process.pid}.${Date.now()}.${staged.length}.tmp`;
      await writeFile(tempPath, content, 'utf8');
      staged.push({ filePath, tempPath });
    }
    for (const { filePath, tempPath } of staged) {
      await rename(tempPath, filePath);
      committed.push(filePath);
    }
  } catch (error) {
    await Promise.all(staged.map(({ tempPath }) => rm(tempPath, { force: true }).catch(() => {})));
    const rollbackErrors = [];
    for (const filePath of committed.reverse()) {
      const original = originals.get(filePath);
      try {
        if (!original.exists) {
          await rm(filePath, { force: true });
          continue;
        }
        const rollbackPath = `${filePath}.${process.pid}.${Date.now()}.rollback`;
        await writeFile(rollbackPath, original.content, 'utf8');
        await rename(rollbackPath, filePath);
      } catch (rollbackError) {
        rollbackErrors.push(`${filePath}: ${rollbackError.message}`);
      }
    }
    if (rollbackErrors.length) {
      throw new Error(`${error.message}\nНе удалось полностью откатить:\n- ${rollbackErrors.join('\n- ')}`);
    }
    throw error;
  }
}

async function findOrphanedGeneratedArticles(posts, locale = 'ru') {
  const root = localeConfig(locale).rootDir;
  const expected = new Set(posts.map((post) => post.slug));
  const entries = await readdir(root, { withFileTypes: true }).catch((error) => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  const orphaned = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === '_preview' || expected.has(entry.name)) continue;
    const candidateDir = path.resolve(root, entry.name);
    if (path.dirname(candidateDir) !== path.resolve(root)) continue;

    const candidateIndex = path.join(candidateDir, 'index.html');
    let content = '';
    try {
      content = await readFile(candidateIndex, 'utf8');
    } catch {
      continue;
    }
    if (!content.includes(GENERATED_MARKER)) continue;
    orphaned.push(candidateDir);
  }
  return orphaned;
}

async function removeOrphanedGeneratedArticles(posts) {
  const orphaned = (
    await Promise.all(LOCALE_KEYS.map((locale) => findOrphanedGeneratedArticles(posts, locale)))
  ).flat();
  for (const candidateDir of orphaned) {
    await rm(candidateDir, { recursive: true, force: true });
  }
}

async function buildSite() {
  const [data, staticPages] = await Promise.all([readJson(DATA_FILE), readStaticSitePages()]);
  const posts = await preparePublishedPosts(data);
  const files = renderGeneratedFiles(posts, staticPages);
  await writeGeneratedFiles(files);
  await removeOrphanedGeneratedArticles(posts);

  return posts;
}

async function previewDraft(draftPath) {
  const resolvedDraft = path.resolve(SITE_ROOT, draftPath);
  const post = await readJson(resolvedDraft);
  const errors = validatePost(post, { allowDraft: true });
  if (errors.length) throw new Error(`Черновик не прошёл проверку:\n- ${errors.join('\n- ')}`);
  await Promise.all(LOCALE_KEYS.map((locale) => assertHeroExists(localizePost(post, locale))));

  const data = await readJson(DATA_FILE);
  const publishedPosts = await preparePublishedPosts(data);
  const previewFiles = [];
  for (const locale of LOCALE_KEYS) {
    const localizedPost = localizePost(post, locale);
    const localizedPublished = publishedPosts.map((published) => localizePost(published, locale));
    const previewPosts = [
      localizedPost,
      ...localizedPublished.filter((published) => published.slug !== post.slug)
    ];
    const root = locale === 'ru' ? PREVIEW_ROOT : EN_PREVIEW_ROOT;
    const previewDir = path.join(root, post.slug);
    await mkdir(previewDir, { recursive: true });
    const articlePreview = path.join(previewDir, 'index.html');
    const listingPreview = path.join(previewDir, 'listing.html');
    await Promise.all([
      writeFile(articlePreview, renderArticle(localizedPost, { preview: true, locale }), 'utf8'),
      writeFile(
        listingPreview,
        renderIndex(previewPosts, { previewSlug: post.slug, locale }),
        'utf8'
      )
    ]);
    previewFiles.push(`${locale.toUpperCase()} статья: ${articlePreview}`);
    previewFiles.push(`${locale.toUpperCase()} лента: ${listingPreview}`);
  }
  return previewFiles.join('\n');
}

async function publishDraft(draftPath, { update = false } = {}) {
  const resolvedDraft = path.resolve(SITE_ROOT, draftPath);
  const draft = await readJson(resolvedDraft);
  draft.status = 'published';
  const errors = validatePost(draft);
  if (errors.length) throw new Error(`Публикация не прошла проверку:\n- ${errors.join('\n- ')}`);
  await Promise.all(LOCALE_KEYS.map((locale) => assertHeroExists(localizePost(draft, locale))));

  const [data, staticPages] = await Promise.all([readJson(DATA_FILE), readStaticSitePages()]);
  const existingIndex = data.posts.findIndex((post) => post.slug === draft.slug);
  if (existingIndex >= 0 && !update) {
    throw new Error(`Материал ${draft.slug} уже существует. Для осознанного обновления добавьте --update.`);
  }
  if (existingIndex < 0 && update) {
    throw new Error(`Материал ${draft.slug} не существует: --update применим только к опубликованному slug.`);
  }
  if (existingIndex >= 0) {
    const existing = data.posts[existingIndex];
    if (draft.datePublished !== existing.datePublished) {
      throw new Error('--update не может менять исходную datePublished существующего материала.');
    }
    if (new Date(draft.dateModified) <= new Date(existing.dateModified)) {
      throw new Error('--update требует dateModified позднее текущей версии материала.');
    }
    data.posts[existingIndex] = draft;
  } else {
    data.posts.push(draft);
  }

  const posts = await preparePublishedPosts(data);
  const files = renderGeneratedFiles(posts, staticPages);

  // DATA_FILE is committed last: after a crash, a retry rebuilds from the previous
  // canonical index; once DATA_FILE changes, every generated artifact is already final.
  files.set(DATA_FILE, `${JSON.stringify(data, null, 2)}\n`);
  await writeGeneratedFiles(files);
  await removeOrphanedGeneratedArticles(posts);
  return posts;
}

async function validateGenerated() {
  const [data, staticPages] = await Promise.all([readJson(DATA_FILE), readStaticSitePages()]);
  const posts = await preparePublishedPosts(data);
  const expectedFiles = renderGeneratedFiles(posts, staticPages);

  for (const [file, expected] of expectedFiles) {
    const content = await readFile(file, 'utf8');
    if (!content.trim()) throw new Error(`Пустой сгенерированный файл: ${file}`);
    if (content !== expected) {
      throw new Error(`Сгенерированный файл устарел: ${file}. Запустите npm run news:build.`);
    }
  }

  const orphaned = (
    await Promise.all(LOCALE_KEYS.map((locale) => findOrphanedGeneratedArticles(posts, locale)))
  ).flat();
  if (orphaned.length) {
    throw new Error(
      `Найдены лишние сгенерированные страницы:\n- ${orphaned.map((item) => path.relative(SITE_ROOT, item)).join('\n- ')}`
    );
  }

  for (const sourcePost of posts) {
    for (const locale of LOCALE_KEYS) {
      const config = localeConfig(locale);
      const post = localizePost(sourcePost, locale);
      const html = await readFile(articlePath(post, locale), 'utf8');
      const label = `${locale}/${post.slug}`;
      if ((html.match(/<h1\b/g) || []).length !== 1) {
        throw new Error(`${label}: нужен ровно один H1.`);
      }
      if (!html.includes(`<html lang="${config.htmlLang}">`)) {
        throw new Error(`${label}: отсутствует корректный html lang.`);
      }
      if (!html.includes(`<link rel="canonical" href="${articleUrl(post, locale)}">`)) {
        throw new Error(`${label}: отсутствует self-canonical.`);
      }
      for (const [language, href] of [
        ['ru', articleUrl(post, 'ru')],
        ['en', articleUrl(post, 'en')],
        ['x-default', articleUrl(post, 'ru')]
      ]) {
        if (!html.includes(`<link rel="alternate" hreflang="${language}" href="${href}">`)) {
          throw new Error(`${label}: отсутствует hreflang="${language}".`);
        }
      }
      const otherLocale = locale === 'ru' ? 'en' : 'ru';
      const switchHref = `${localeConfig(otherLocale).rootPath}${post.slug}/`;
      if (!html.includes(`href="${switchHref}"`)) {
        throw new Error(`${label}: переключатель не ведёт на парную языковую страницу.`);
      }
      if (!html.includes('"@type": "NewsArticle"')) {
        throw new Error(`${label}: отсутствует NewsArticle JSON-LD.`);
      }
      if (!html.includes(`"inLanguage": "${config.bcp47}"`)) {
        throw new Error(`${label}: NewsArticle содержит неверный inLanguage.`);
      }
      if (/meta name="keywords"/i.test(html)) throw new Error(`${label}: meta keywords запрещён.`);
      const articleFooter = html.match(/<footer class="article-footer">([\s\S]*?)<\/footer>/)?.[1] ?? '';
      const expectedContact = (
        `href="${EDITOR_TELEGRAM_URL}" rel="noopener noreferrer" target="_blank" ` +
        `aria-label="${escapeHtml(config.editorContactLabel)}"`
      );
      if (!articleFooter.includes(expectedContact)) {
        throw new Error(`${label}: отсутствует Telegram-контакт редакции.`);
      }
      if (!html.includes('data-article-toc')) {
        throw new Error(`${label}: отсутствует навигация по материалу.`);
      }
      if (!html.includes('<div class="article-content" id="article-content" tabindex="-1">')) {
        throw new Error(`${label}: skip-link ведёт на нефокусируемое содержимое статьи.`);
      }
      if (!html.includes('href="/order.html?type=standard" data-news-cta')) {
        throw new Error(`${label}: CTA должен сохранять общий target /order.html?type=standard.`);
      }
      if (/class="article-table-wrap[^"]*"[^>]*tabindex="0"/.test(html)) {
        throw new Error(`${label}: таблица не должна быть постоянной лишней Tab-остановкой.`);
      }
      if (locale === 'en' && /[А-Яа-яЁё]/u.test(html)) {
        throw new Error(`${label}: в английском HTML обнаружена кириллица.`);
      }
    }
  }

  for (const locale of LOCALE_KEYS) {
    const rss = await readFile(path.join(localeConfig(locale).rootDir, 'rss.xml'), 'utf8');
    if (rss.includes('/order.html?type=standard')) {
      throw new Error(`${locale.toUpperCase()} RSS не должен содержать коммерческий CTA.`);
    }
  }
  const rssCtaSentinel = 'BOOST_MLBB_RSS_CTA_SENTINEL';
  const rssEditorialSentinel = 'BOOST_MLBB_RSS_EDITORIAL_SENTINEL';
  const rssProbePost = {
    slug: 'rss-cta-sentinel',
    title: 'Проверка RSS',
    excerpt: 'Проверка исключения коммерческого блока.',
    category: 'Проверка',
    datePublished: new Date().toISOString(),
    dateModified: new Date().toISOString(),
    hero: { src: '/images/news/rss-sentinel.jpg', width: 1600, height: 900 },
    blocks: [
      { type: 'paragraph', text: rssEditorialSentinel },
      {
        type: 'cta',
        id: 'rss-cta',
        eyebrow: rssCtaSentinel,
        title: rssCtaSentinel,
        text: rssCtaSentinel,
        button: rssCtaSentinel,
        href: rssCtaSentinel,
        note: rssCtaSentinel,
        position: 'rss-probe'
      }
    ]
  };
  for (const locale of LOCALE_KEYS) {
    const rssProbe = renderRss([rssProbePost], locale);
    if (rssProbe.includes(rssCtaSentinel)) {
      throw new Error(`${locale.toUpperCase()} RSS-рендерер не должен включать коммерческий CTA.`);
    }
    if (!rssProbe.includes(`<yandex:full-text>${rssEditorialSentinel}</yandex:full-text>`)) {
      throw new Error(`${locale.toUpperCase()} RSS должен сохранять полный редакционный текст.`);
    }
  }

  const sitemap = await readFile(path.join(SITE_ROOT, 'sitemap.xml'), 'utf8');
  for (const post of posts) {
    for (const locale of LOCALE_KEYS) {
      if (!sitemap.includes(`<loc>${articleUrl(post, locale)}</loc>`)) {
        throw new Error(`sitemap.xml не содержит ${locale}/${post.slug}.`);
      }
    }
  }

  if (posts.length) {
    const broken = structuredClone(posts[0]);
    broken.translations.en.blocks = broken.translations.en.blocks.slice(1);
    const negativeErrors = validatePost(broken);
    if (!negativeErrors.some((error) => error.includes('translations.en.blocks'))) {
      throw new Error('Негативная проверка не обнаружила структурно неполный английский перевод.');
    }
  }

  return posts;
}

async function main() {
  const command = process.argv[2] || 'build';
  if (command === 'build') {
    const posts = await withNewsWriteLock(buildSite);
    console.log(`Собрано публикаций: ${posts.length}`);
    return;
  }
  if (command === 'validate') {
    const posts = await validateGenerated();
    console.log(`Проверка пройдена. Публикаций: ${posts.length}`);
    return;
  }
  if (command === 'preview') {
    if (!process.argv[3]) throw new Error('Укажите путь к JSON-черновику.');
    console.log(`Предпросмотр: ${await previewDraft(process.argv[3])}`);
    return;
  }
  if (command === 'publish') {
    if (!process.argv[3]) throw new Error('Укажите путь к JSON-черновику.');
    const posts = await withNewsWriteLock(() => (
      publishDraft(process.argv[3], { update: process.argv.includes('--update') })
    ));
    console.log(`Публикация собрана. Всего материалов: ${posts.length}`);
    return;
  }
  throw new Error(`Неизвестная команда: ${command}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
