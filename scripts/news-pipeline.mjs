function escapeHtml(value = '') {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function escapeXml(value = '') {
  return escapeHtml(value);
}

function safeJson(value) {
  return JSON.stringify(value, null, 2).replaceAll('<', '\\u003c');
}

function absoluteUrl(value) {
  if (/^https?:\/\//i.test(value)) return value;
  return `${SITE_ORIGIN}${value.startsWith('/') ? value : `/${value}`}`;
}

function localeConfig(locale = 'ru') {
  const config = NEWS_LOCALES[locale];
  if (!config) throw new Error(`Неподдерживаемая локаль новостей: ${locale}`);
  return config;
}

function localizePost(post, locale = 'ru') {
  if (locale === 'ru') {
    const localized = { ...post };
    delete localized.translations;
    return localized;
  }

  const translation = post.translations?.[locale];
  if (!translation || typeof translation !== 'object' || Array.isArray(translation)) {
    throw new Error(`${post.slug || 'Материал'}: отсутствует перевод translations.${locale}.`);
  }
  const localized = {
    ...post,
    ...translation,
    hero: { ...post.hero, ...(translation.hero || {}) },
    sources: post.sources
  };
  delete localized.translations;
  return localized;
}

